def tip(key: str) -> str:
    """A small "?" that shows the explanation on hover (or tap/focus on touch screens)."""
    t = TERMS.get(key)
    if not t:
        return ""
    return f'<span class="tip" tabindex="0" role="img" aria-label="{html.escape(t[1])}" data-tip="{html.escape(t[1])}">?</span>'


def legend_html(keys: list[str], title: str = "Τι σημαίνουν οι ετικέτες") -> str:
    items = "".join(f"<dt>{html.escape(TERMS[k][0])}</dt><dd>{html.escape(TERMS[k][1])}</dd>" for k in keys if k in TERMS)
    return f'<details class="card legend"><summary><b>{html.escape(title)}</b></summary><dl>{items}</dl></details>'


def as_dict() -> dict:
    return {k: {"label": v[0], "text": v[1]} for k, v in TERMS.items()}
